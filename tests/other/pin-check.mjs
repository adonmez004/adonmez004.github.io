import { chromium } from "playwright";
import http from "node:http";
const LOCAL = process.env.INSPECTOR;
const html = `<!doctype html><html><head><meta charset="utf-8"><style id="s">.card { color: red; padding: 10px; }</style></head><body><main><p class="card" id="card">card</p></main><script defer src="https://demo.frontendmentorsolutions.io/inspector.js"></script></body></html>`;
const srv = http.createServer((q, r) => { r.setHeader("content-type", "text/html"); r.end(html); }).listen(0);
const browser = await chromium.launch();
const page = await browser.newPage();
await page.route("https://demo.frontendmentorsolutions.io/inspector.js", (r) => r.fulfill({ path: LOCAL, contentType: "text/javascript" }));
await page.goto(`http://127.0.0.1:${srv.address().port}/`, { waitUntil: "networkidle" });
const host = page.locator("fm-inspector");
await host.locator(".fab").click(); await page.waitForTimeout(600);
await host.locator('[role="tab"]', { hasText: /css/i }).first().click(); await page.waitForTimeout(300);
const css = () => page.evaluate(() => document.getElementById("s").sheet.cssRules[0].style.cssText);
const edit = (v) => page.evaluate((v) => { const i = document.querySelector("fm-inspector"); const d = i.store.allDecls.find((d) => d.model.selector === ".card" && d.prop === "color" && d.on); const before = i.state(d); d.value = v; i.apply(d); i.record([{ d, before, after: i.state(d) }]); i.pins.add(d); }, v);
await edit("blue");
await page.evaluate(() => { document.getElementById("s").sheet.cssRules[0].style.setProperty("background", "yellow"); }); await page.waitForTimeout(1300);
console.log("pinned, page added, polled:", await css());
await page.evaluate(() => document.querySelector("fm-inspector").reset()); await page.waitForTimeout(1300);
console.log("after Reset:", await css());
await edit("green"); await page.waitForTimeout(300);
console.log("after next edit:", await css(), "(expect background kept)");
await browser.close(); srv.close();
